ALTER TABLE app_users ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE app_users ADD COLUMN auth_version BIGINT NOT NULL DEFAULT 0;

CREATE TABLE account_tokens (
    token_hash VARCHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    purpose VARCHAR(24) NOT NULL,
    target_email VARCHAR(160),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at TIMESTAMP WITH TIME ZONE,
    request_ip VARCHAR(64),
    CONSTRAINT ck_account_token_purpose CHECK (purpose IN ('VERIFY_EMAIL', 'CHANGE_EMAIL', 'RESET_PASSWORD'))
);
CREATE INDEX idx_account_tokens_user_purpose ON account_tokens(user_id, purpose, created_at DESC);

CREATE TABLE account_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT REFERENCES app_users(id),
    subject_id BIGINT REFERENCES app_users(id),
    action VARCHAR(48) NOT NULL,
    detail VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE support_tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    category VARCHAR(32) NOT NULL,
    subject VARCHAR(160) NOT NULL,
    description VARCHAR(3000) NOT NULL,
    reference_type VARCHAR(24),
    reference_id VARCHAR(64),
    status VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    admin_note VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_support_ticket_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED'))
);
CREATE INDEX idx_support_tickets_user_created ON support_tickets(user_id, created_at DESC);

