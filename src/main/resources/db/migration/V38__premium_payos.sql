-- Additive tables only. Existing learning records and user roles are retained.
CREATE TABLE premium_accounts (
    user_id BIGINT PRIMARY KEY REFERENCES app_users(id) ON DELETE CASCADE,
    premium_until TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE premium_daily_usage (
    user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    usage_day DATE NOT NULL,
    practice_count INTEGER NOT NULL DEFAULT 0 CHECK (practice_count >= 0),
    ai_count INTEGER NOT NULL DEFAULT 0 CHECK (ai_count >= 0),
    PRIMARY KEY (user_id, usage_day)
);
CREATE TABLE payment_orders (
    order_code BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100000) PRIMARY KEY,
    user_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
    amount_vnd INTEGER NOT NULL CHECK (amount_vnd > 0),
    duration_days INTEGER NOT NULL CHECK (duration_days > 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('CREATING','PENDING','PAID','EXPIRED','CANCELLED')),
    payment_link_id VARCHAR(64) UNIQUE,
    checkout_url VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    paid_at TIMESTAMP WITH TIME ZONE,
    payment_reference VARCHAR(150) UNIQUE
);
CREATE INDEX payment_orders_user_created ON payment_orders(user_id, created_at);
