CREATE TABLE lessons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(80) NOT NULL UNIQUE,
    title VARCHAR(140) NOT NULL,
    description VARCHAR(500) NOT NULL,
    level VARCHAR(2) NOT NULL,
    topic VARCHAR(60) NOT NULL,
    estimated_minutes INTEGER NOT NULL,
    display_order INTEGER NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_lesson_level CHECK (level IN ('A1', 'A2', 'B1', 'B2'))
);

CREATE INDEX idx_lessons_level_order ON lessons(level, display_order);

CREATE TABLE lesson_sentences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    position_index INTEGER NOT NULL,
    transcript VARCHAR(1000) NOT NULL,
    audio_url VARCHAR(500),
    speech_rate DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    CONSTRAINT uk_sentence_lesson_position UNIQUE (lesson_id, position_index)
);

CREATE INDEX idx_sentences_lesson_position ON lesson_sentences(lesson_id, position_index);

CREATE TABLE practice_sessions (
    id VARCHAR(36) PRIMARY KEY,
    learner_id VARCHAR(80) NOT NULL,
    lesson_id BIGINT NOT NULL REFERENCES lessons(id),
    status VARCHAR(20) NOT NULL,
    current_sentence_position INTEGER NOT NULL DEFAULT 1,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    total_replays INTEGER NOT NULL DEFAULT 0,
    hint_count INTEGER NOT NULL DEFAULT 0,
    reveal_count INTEGER NOT NULL DEFAULT 0,
    known_missed_count INTEGER NOT NULL DEFAULT 0,
    unknown_count INTEGER NOT NULL DEFAULT 0,
    total_practice_seconds INTEGER NOT NULL DEFAULT 0,
    first_attempt_accuracy DOUBLE PRECISION NOT NULL DEFAULT 0,
    final_accuracy DOUBLE PRECISION NOT NULL DEFAULT 0,
    overall_score DOUBLE PRECISION NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_session_status CHECK (status IN ('IN_PROGRESS', 'COMPLETED'))
);

CREATE INDEX idx_sessions_learner_status_completed
    ON practice_sessions(learner_id, status, completed_at);

CREATE TABLE sentence_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    practice_session_id VARCHAR(36) NOT NULL REFERENCES practice_sessions(id) ON DELETE CASCADE,
    sentence_id BIGINT NOT NULL REFERENCES lesson_sentences(id),
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    time_spent_seconds INTEGER NOT NULL DEFAULT 0,
    replay_count INTEGER NOT NULL DEFAULT 0,
    first_letter_hint_count INTEGER NOT NULL DEFAULT 0,
    word_reveal_count INTEGER NOT NULL DEFAULT 0,
    full_reveal_used BOOLEAN NOT NULL DEFAULT FALSE,
    replayed_after_reveal BOOLEAN NOT NULL DEFAULT FALSE,
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_attempt_session_sentence UNIQUE (practice_session_id, sentence_id)
);

CREATE INDEX idx_sentence_attempt_session ON sentence_attempts(practice_session_id);

CREATE TABLE word_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sentence_attempt_id BIGINT NOT NULL REFERENCES sentence_attempts(id) ON DELETE CASCADE,
    word_index INTEGER NOT NULL,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    first_attempt_correct BOOLEAN,
    final_correct BOOLEAN NOT NULL DEFAULT FALSE,
    first_letter_hint BOOLEAN NOT NULL DEFAULT FALSE,
    revealed BOOLEAN NOT NULL DEFAULT FALSE,
    last_answer VARCHAR(200),
    error_type VARCHAR(30),
    CONSTRAINT uk_word_attempt_index UNIQUE (sentence_attempt_id, word_index),
    CONSTRAINT ck_word_error_type CHECK (error_type IS NULL OR error_type IN ('KNOWN_BUT_MISSED', 'UNKNOWN'))
);

CREATE INDEX idx_word_attempt_sentence ON word_attempts(sentence_attempt_id, word_index);
