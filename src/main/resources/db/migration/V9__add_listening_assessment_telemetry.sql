ALTER TABLE practice_sessions ADD COLUMN first_exposure BOOLEAN NOT NULL DEFAULT FALSE;

UPDATE practice_sessions current_session
SET first_exposure = TRUE
WHERE current_session.started_at = (
    SELECT MIN(candidate.started_at)
    FROM practice_sessions candidate
    WHERE candidate.user_id = current_session.user_id
      AND candidate.lesson_id = current_session.lesson_id
);

