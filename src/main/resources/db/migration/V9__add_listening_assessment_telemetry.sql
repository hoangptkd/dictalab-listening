CREATE TABLE word_attempt_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word_attempt_id BIGINT NOT NULL REFERENCES word_attempts(id) ON DELETE CASCADE,
    attempt_number INTEGER NOT NULL,
    raw_answer VARCHAR(200) NOT NULL,
    normalized_answer VARCHAR(200) NOT NULL,
    correct BOOLEAN NOT NULL,
    response_time_ms BIGINT NOT NULL DEFAULT 0,
    error_category VARCHAR(30),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_word_attempt_event_number UNIQUE (word_attempt_id, attempt_number),
    CONSTRAINT ck_word_attempt_event_number CHECK (attempt_number > 0),
    CONSTRAINT ck_word_attempt_response_time CHECK (response_time_ms >= 0),
    CONSTRAINT ck_listening_error_category CHECK (
        error_category IS NULL OR error_category IN (
            'OMISSION', 'INSERTION', 'SUBSTITUTION', 'SPELLING', 'WORD_FORM', 'WORD_ORDER'
        )
    )
);

CREATE INDEX idx_word_attempt_event_word ON word_attempt_events(word_attempt_id, attempt_number);
