CREATE TABLE lesson_preview_words (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
    position_index INTEGER NOT NULL,
    word VARCHAR(100) NOT NULL,
    audio_start_seconds DOUBLE PRECISION,
    audio_end_seconds DOUBLE PRECISION,
    CONSTRAINT uk_preview_word_lesson_position UNIQUE (lesson_id, position_index),
    CONSTRAINT ck_preview_word_audio_range CHECK (
        (audio_start_seconds IS NULL AND audio_end_seconds IS NULL)
        OR (audio_start_seconds >= 0 AND audio_end_seconds > audio_start_seconds)
    )
);

CREATE INDEX idx_preview_words_lesson ON lesson_preview_words(lesson_id, position_index);
