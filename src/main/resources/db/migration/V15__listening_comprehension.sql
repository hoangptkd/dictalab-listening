CREATE TABLE listening_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT NOT NULL REFERENCES lessons(id),
    audio_url VARCHAR(500) NOT NULL,
    title VARCHAR(140) NOT NULL,
    level VARCHAR(2) NOT NULL,
    duration_seconds DOUBLE PRECISION NOT NULL,
    content_json TEXT NOT NULL,
    published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_listening_audio UNIQUE (lesson_id, audio_url),
    CONSTRAINT ck_listening_duration CHECK (duration_seconds > 0)
);

CREATE TABLE listening_sessions (
    id VARCHAR(36) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    unit_id BIGINT NOT NULL REFERENCES listening_units(id),
    mode VARCHAR(12) NOT NULL,
    stage VARCHAR(24) NOT NULL,
    current_pass INTEGER NOT NULL DEFAULT 1,
    first_exposure BOOLEAN NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_listening_mode CHECK (mode IN ('ONE_PASS', 'TWO_PASS')),
    CONSTRAINT ck_listening_pass CHECK (current_pass IN (1, 2))
);
CREATE INDEX idx_listening_sessions_user ON listening_sessions(user_id, started_at DESC);

CREATE TABLE listening_passes (
    session_id VARCHAR(36) NOT NULL REFERENCES listening_sessions(id) ON DELETE CASCADE,
    pass_number INTEGER NOT NULL,
    playback_token VARCHAR(36),
    playback_started_at TIMESTAMP WITH TIME ZONE,
    playback_ended_at TIMESTAMP WITH TIME ZONE,
    recall_text TEXT,
    recall_submitted_at TIMESTAMP WITH TIME ZONE,
    answers_json TEXT,
    answers_submitted_at TIMESTAMP WITH TIME ZONE,
    comprehension_score DOUBLE PRECISION,
    recall_score DOUBLE PRECISION,
    recall_result_json TEXT,
    grading_status VARCHAR(16) NOT NULL DEFAULT 'NOT_REQUESTED',
    grading_attempts INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (session_id, pass_number),
    CONSTRAINT ck_listening_pass_number CHECK (pass_number IN (1, 2))
);
CREATE INDEX idx_listening_grading ON listening_passes(grading_status);

CREATE TABLE listening_review_marks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(36) NOT NULL REFERENCES listening_sessions(id) ON DELETE CASCADE,
    sentence_id BIGINT NOT NULL REFERENCES lesson_sentences(id),
    difficulty_type VARCHAR(24) NOT NULL,
    note VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_listening_difficulty CHECK (difficulty_type IN ('NOT_HEARD', 'HEARD_NOT_UNDERSTOOD'))
);

