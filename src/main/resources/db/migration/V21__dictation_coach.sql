-- Additive tables only; no updates to existing scores, sessions, or transcripts.
CREATE TABLE dictation_coach_reports (
    session_id VARCHAR(36) PRIMARY KEY REFERENCES practice_sessions(id) ON DELETE CASCADE,
    report_json TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE dictation_error_bank (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    session_id VARCHAR(36) NOT NULL REFERENCES practice_sessions(id) ON DELETE CASCADE,
    item_id VARCHAR(60) NOT NULL,
    item_json TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_dictation_error_bank UNIQUE (user_id, session_id, item_id)
);
CREATE INDEX idx_dictation_error_bank_user ON dictation_error_bank(user_id, created_at);
